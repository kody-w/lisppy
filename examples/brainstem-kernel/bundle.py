"""bundle: the LisPy Brainstem as ONE file (a kernel-kind part for grail-layers).

Embeds lisp.py (lispy-core@1 reference, sha-pinned), its stdlib files, llms.txt, brainstem.lispy and the host.
At start the bundle unpacks them into a content-hash-keyed folder beside itself (shiv/pex lesson: idempotent,
never beside the owner's data), verifies every sha, and runs the host from there. The owner's data stays where
the supervisor points it (AGENTS_PATH, SOUL_PATH, BRAINSTEM_DATA_DIR).

  python3 bundle.py            -> writes lispy_brainstem.py and prints its sha256
"""
import hashlib
import os
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
LISPPY = Path(os.environ.get("LISPPY_DIR") or (HERE / "lisppy" if (HERE / "lisppy").exists() else HERE.parent.parent)).resolve()
FILES = {
    "lisppy/lisp.py": LISPPY / "lisp.py",
    "lisppy/stdlib.lisp": LISPPY / "stdlib.lisp",
    "lisppy/core-stdlib.lisp": LISPPY / "core-stdlib.lisp",
    "lisppy/llms.txt": LISPPY / "llms.txt",
    "brainstem.lispy": HERE / "brainstem.lispy",
    "lispy_host.py": HERE / "lispy_host.py",
    "VERSION": HERE / "VERSION",
}
TEMPLATE = '''#!/usr/bin/env python3
"""lispy_brainstem: a RAPP Brainstem whose kernel is LisPy (lispy-core@1), as one file.
Generated by bundle.py from kody-w/lisppy {lisppy_version} (lisp.py sha256 {lisp_sha}) and the LisPy host.
Runs as a kernel-kind part under grail-layers, or on its own: python3 lispy_brainstem.py (PORT, AGENTS_PATH, SOUL_PATH).
Nothing to install: python3 only.
"""
import base64, hashlib, os, runpy, sys, zlib
from pathlib import Path

BUNDLE = {files_literal}
BUNDLE_SHA = "{bundle_sha}"


def unpack():
    here = Path(__file__).resolve().parent
    root = here / ".bundle" / BUNDLE_SHA[:16]
    for rel, (sha, blob) in BUNDLE.items():
        p = root / rel
        if p.is_file() and hashlib.sha256(p.read_bytes()).hexdigest() == sha:
            continue
        data = zlib.decompress(base64.b64decode(blob))
        if hashlib.sha256(data).hexdigest() != sha:
            sys.exit(f"[lispy_brainstem] embedded {{rel}} does not match its sha256; refusing to run")
        p.parent.mkdir(parents=True, exist_ok=True)
        tmp = p.with_suffix(p.suffix + ".tmp"); tmp.write_bytes(data); os.replace(tmp, p)
    return root


if __name__ == "__main__":
    root = unpack()
    os.environ["LISPPY_DIR"] = str(root / "lisppy")
    os.environ.setdefault("BRAINSTEM_DATA_DIR", str(Path(__file__).resolve().parent / ".brainstem_data"))
    sys.argv = [str(root / "lispy_host.py")] + sys.argv[1:]
    runpy.run_path(str(root / "lispy_host.py"), run_name="__main__")
'''


def main():
    import base64, zlib
    files, h = {}, hashlib.sha256()
    for rel, src in FILES.items():
        b = src.read_bytes()
        files[rel] = (hashlib.sha256(b).hexdigest(), base64.b64encode(zlib.compress(b, 9)).decode())
        h.update(rel.encode() + b"\0" + b)
    out = TEMPLATE.format(files_literal=json.dumps(files, indent=0), bundle_sha=h.hexdigest(),
                          lisp_sha=files["lisppy/lisp.py"][0][:12], lisppy_version=(LISPPY / "VERSION").read_text().strip())
    dst = HERE / "lispy_brainstem.py"
    dst.write_text(out)
    print(dst, len(out), "bytes", hashlib.sha256(dst.read_bytes()).hexdigest())


if __name__ == "__main__":
    main()
